"""Offline training/export only. The frozen model executes in Verilog, not here."""
from pathlib import Path
import hashlib
import json
import numpy as np
import sklearn
from sklearn.datasets import load_digits
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import train_test_split

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'model' / 'digits'
SEED = 20261027


def save_hex(name, values, width):
    mask = (1 << width) - 1
    (OUT / name).write_text(''.join(f'{int(v) & mask:0{width//4}x}\n' for v in values), encoding='utf-8', newline='\n')


def main():
    OUT.mkdir(exist_ok=True)
    data = load_digits()
    x = data.data.astype(np.float64) / 8.0 - 1.0
    y = data.target
    train, rest = train_test_split(np.arange(len(y)), test_size=0.4, stratify=y, random_state=SEED)
    calibration, test = train_test_split(rest, test_size=0.5, stratify=y[rest], random_state=SEED)
    clf = LogisticRegression(C=1.0, solver='lbfgs', max_iter=3000, tol=1e-10)
    clf.fit(x[train], y[train])
    if clf.n_iter_.max() >= 3000:
        raise RuntimeError('Training did not converge')
    report = {'dataset': 'sklearn load_digits (8x8), project-specific stratified split',
              'seed': SEED, 'sklearn': sklearn.__version__, 'numpy': np.__version__,
              'normalization': 'pixel / 8 - 1', 'rounding': 'numpy rint, ties to even',
              'training': {'C': 1.0, 'solver': 'lbfgs', 'max_iter': 3000, 'tol': 1e-10},
              'split_indices': {'train': train.tolist(), 'calibration': calibration.tolist(), 'test': test.tolist()},
              'count': {'train': len(train), 'calibration': len(calibration), 'test': len(test)},
              'accuracy_budget_percentage_points': 1.0,
              'floating_test_correct': int((clf.predict(x[test]) == y[test]).sum()), 'modes': {}}
    (OUT / 'floating_model.json').write_text(json.dumps({'weights': clf.coef_.tolist(),
        'bias': clf.intercept_.tolist()}, indent=2) + '\n', encoding='utf-8', newline='\n')
    save_hex('labels.hex', y[test], 8)
    save_hex('float_predictions.hex', clf.predict(x[test]), 8)
    cases, biases = [], []
    for bits in (8, 4):
        limit = (1 << (bits - 1)) - 1
        input_scale = 1.0 / limit
        # Select GLOBAL weight clipping on calibration only; one scale across
        # all classes makes raw signed integer score comparisons meaningful.
        candidates = []
        for fraction in (1.0, 0.9, 0.8, 0.7, 0.6):
            weight_scale = float(np.abs(clf.coef_).max() * fraction / limit)
            qw = np.clip(np.rint(clf.coef_ / weight_scale), -limit, limit).astype(np.int64)
            qb = np.rint(clf.intercept_ / (input_scale * weight_scale)).astype(np.int64)
            qx = np.clip(np.rint(x[calibration] / input_scale), -limit, limit).astype(np.int64)
            correct = int(((qx @ qw.T + qb).argmax(axis=1) == y[calibration]).sum())
            candidates.append((correct, fraction, weight_scale, qw, qb))
        correct, fraction, weight_scale, qw, qb = max(candidates, key=lambda v: (v[0], v[1]))
        qx = np.clip(np.rint(x[test] / input_scale), -limit, limit).astype(np.int64)
        scores = qx @ qw.T + qb
        # Bound every possible normalized input, not just this test set.
        bound = np.abs(qw).sum(axis=1) * limit + np.abs(qb)
        assert int(bound.max()) < 2**31
        pred = scores.argmax(axis=1)
        drop = 100.0 * (report['floating_test_correct'] - int((pred == y[test]).sum())) / len(test)
        report['modes'][str(bits)] = {'input_scale': input_scale, 'weight_scale': weight_scale,
            'clipping_fraction': fraction, 'calibration_correct': correct,
            'calibration_candidates': [{'fraction': v[1], 'correct': v[0]} for v in candidates],
            'test_correct': int((pred == y[test]).sum()), 'accuracy_drop_percentage_points': drop,
            'meets_budget': drop <= 1.0, 'maximum_accumulator_bound': int(bound.max())}
        if bits == 4:
            packed_x = (qx[:, 0::2] & 15) | ((qx[:, 1::2] & 15) << 4)
            packed_w = (qw[:, 0::2] & 15) | ((qw[:, 1::2] & 15) << 4)
        else:
            packed_x, packed_w = qx & 255, qw & 255
        save_hex(f'features_int{bits}.hex', packed_x.flat, 8)
        save_hex(f'scores_int{bits}.hex', scores.flat, 32)
        save_hex(f'predictions_int{bits}.hex', pred, 8)
        for address, value in enumerate(packed_w.flat):
            key = address + (1024 if bits == 4 else 0)
            cases.append(f"            11'd{key}: weight = 8'h{int(value):02x};")
        for c, value in enumerate(qb):
            key = c + (16 if bits == 4 else 0)
            biases.append(f"            5'd{key}: bias = 32'h{int(value) & 0xffffffff:08x};")
    rom = '''// Generated by scripts/export_digits.py. Frozen trained constants, not control RTL.
module digits_model_rom (
    input wire mode4,
    input wire [9:0] weight_address,
    input wire [3:0] bias_class,
    output reg [7:0] weight,
    output reg signed [31:0] bias
);
    always @* begin
        weight = 8'd0;
        case ({mode4, weight_address})
WEIGHTS
            default: weight = 8'd0;
        endcase
        bias = 32'sd0;
        case ({mode4, bias_class})
BIASES
            default: bias = 32'sd0;
        endcase
    end
endmodule
'''.replace('WEIGHTS', '\n'.join(cases)).replace('BIASES', '\n'.join(biases))
    (ROOT / 'rtl' / 'digits_model_rom.v').write_text(rom, encoding='utf-8', newline='\n')
    files = sorted(OUT.glob('*.hex')) + [ROOT / 'rtl' / 'digits_model_rom.v', OUT / 'floating_model.json']
    report['sha256'] = {p.relative_to(ROOT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
    (OUT / 'metadata.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8', newline='\n')
    print(json.dumps({k: report[k] for k in ('count', 'floating_test_correct', 'modes')}, indent=2))


if __name__ == '__main__':
    main()
